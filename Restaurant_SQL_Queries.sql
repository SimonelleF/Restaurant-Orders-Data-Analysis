# Q13. Do males or females place higher no. of orders ?
select sex, count(o.id) as total_orders
from members m
join orders o
on m.id=o.members_id
group by sex
order by total_orders desc;

# Q14. Which are the popular restaurants among a particular gender?
with Rest_Members as
(select sex,count(o.id) as total_orders ,restaurant_name,city
from members m
join orders o 
on m.id=o.members_id
join restaurants r
on o.restaurants_id=r.id
join cities c
on c.id=r.cities_id
group by sex,restaurant_name,city
)
select * 
from( select  
             sex,
			 restaurant_name,
             city,
             total_orders,
             dense_rank() over(
                               partition by sex
                               order by total_orders desc
                               ) as rnk
from Rest_Members) t
where rnk<=10 ;

