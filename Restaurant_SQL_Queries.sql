# Q18. What is the average order price ? 
select round(avg(total_order),2) as avg_price from orders;

# Q19. Which are the high-end and budget friendly restaurants as per average order price ?
with avg_order_price as
(
select 
       restaurant_name,total_order,city
from orders o 
join restaurants r
on o.restaurants_id=r.id
join cities c
on c.id=r.cities_id
)
select restaurant_name, avg(total_order) as avg_price ,city
from avg_order_price
group by restaurant_name,city
order by avg_price desc;

# Q20. Identify budget-friendly and premium meals as per average meal price.
with avg_meal_price as
(
select 
       meal_type,total_order
from orders o 
join order_details od
on o.id=od.orders_id
join meals me
on me.id=od.meals_id
join meal_types mt
on me.meal_types_id=mt.id
)
select meal_type, avg(total_order) as avg_price
from avg_meal_price
group by meal_type
order by avg_price desc;


# Evaluate customer's spending behaviour
# Q21. Which customers exceed their budget ?
with customer_budget as (
select concat(first_name," ",surname) as name ,monthly_budget as target , total_expense as actual_spending 
from monthly_member_totals mmt)
select  name , target , actual_spending ,
(target-actual_spending) as target_actual
from customer_budget
order by target_actual ;


# Understand restaurants' performance
# Q22. Which are the restaurants that earn high revenue in terms of income percentage / earn the highest payout ?
with restaurant_order_price as
(
select restaurant_name, sum(total_order) as total_order_price,max(income_percentage) as inc_pct
from
orders o 
join restaurants r
on o.restaurants_id=r.id
group by restaurant_name
order by total_order_price desc)

select restaurant_name,total_order_price,round((total_order_price*inc_pct),2) as Revenue from restaurant_order_price 
order by Revenue desc limit 10;
