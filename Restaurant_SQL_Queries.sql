# Analyze platform performance
# Q1. What is the total revenue earned by the food delivery app ?
select sum((total_expense-commission)) as Revenue 
from monthly_member_totals;

# Q2. What is the monthly revenue earned by the food delivery app ?
select month,sum((total_expense-commission)) as Revenue 
from monthly_member_totals
