# Identify popular regions, meals, and restaurant categories among customers
# Q3. Which are the most popular restaurants?
select  restaurant_name,count(o.id) as Order_frequency
from restaurants r
join orders o
on r.id=o.restaurants_id
group by restaurant_name
order by Order_frequency desc limit 10;

# Q4. Which are the popular restaurant categories(restaurant types) ?
select  restaurant_types,count(o.id) as Order_frequency
from restaurant_types rt
join restaurants r
on rt.id=r.restaurant_types_id
join orders o
on r.id=o.restaurants_id
group by restaurant_types
order by Order_frequency desc ;

# Q5. Which are the popular meal types ?
select  meal_type,count(od.id) as Order_frequency
from meal_types mt
join meals m
on mt.id=m.meal_types_id
join order_details od
on m.id=od.meals_id
group by meal_type
order by Order_frequency desc ;

# Q6. Which are the popular meals ?
select meal_name,count(orders_id) as Order_frequency from order_details
join meals
on meals.id=order_details.meals_id
group by meals_id 
order by Order_frequency desc limit 5;

# Q7. Which are the best-performing restaurants in terms of orders placed in each restaurant category ?
WITH Top_rest_categorywise AS (
    SELECT  
        restaurant_types , 
       restaurant_name,
	   count(o.id) as order_count
    FROM restaurant_types rt
    JOIN restaurants r
        ON rt.id = r.restaurant_types_id
	join orders o
    on r.id=o.restaurants_id
    group by restaurant_name,restaurant_types
)
SELECT *
FROM (
    SELECT 
        restaurant_types,
       restaurant_name,
        order_count,
         DENSE_RANK() OVER (
            PARTITION BY restaurant_types
            ORDER BY order_count DESC
        ) AS rnk
    FROM Top_rest_categorywise
) t
WHERE rnk <= 3;

# Q8. Which cities show the highest customer demand based on order frequency?
With City_Orders AS 
(select c.city as City ,o.id as order_id
from cities c
inner join restaurants r
on c.id=r.cities_id
inner join orders o
on r.id=o.restaurants_id)

select City,count(order_id) as num_of_orders
from City_Orders 
group by City 
order by num_of_orders desc;


# Detect loyal customers
# Q9. Identify the most profitable customers for platform in terms of revenue generated by a customer.
select concat(first_name," ",surname) as name,sum((total_expense-commission)) as Revenue 
from monthly_member_totals
group by name
having Revenue>4500
order by revenue desc;

# Q10. Identify the customers who frequently place orders.
select  concat(m.first_name," ",m.surname) as customer_name, sum(order_count) as Total_times_order,m.sex
from members m
inner join monthly_member_totals mmt
on m.id=mmt.members_id
group by m.id
having Total_times_order>=150
order by Total_times_order desc;

# Q11. Who are the top 5 most active customers each month based on order frequency?
WITH Monthwise_top_customer AS (
    SELECT  
        CONCAT(m.first_name, ' ', m.surname) AS customer_name, 
        mmt.order_count,
        mmt.month
    FROM members m
    JOIN monthly_member_totals mmt
        ON m.id = mmt.members_id
)

SELECT *
FROM (
    SELECT 
        customer_name,
        month,
        order_count,
         DENSE_RANK() OVER (
            PARTITION BY month 
            ORDER BY order_count DESC
        ) AS rnk
    FROM Monthwise_top_customer
) t
WHERE rnk <= 5;


